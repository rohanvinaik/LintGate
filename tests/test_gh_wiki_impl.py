# ── _split_design_md ─────────────────────────────────────────────────


class TestSplitDesignMd:
    def test_splits_by_h2_headings(self, tmp_path):
        content = "# Title\n\n## Architecture\n\n" + ("x" * 250) + "\n\n## Config\n\n" + ("y" * 250)
        p = tmp_path / "design.md"
        p.write_text(content)
        pages = _split_design_md(str(p))
        assert "Architecture" in pages
        assert "Config" in pages
        assert pages["Architecture"].startswith("# Architecture")
        assert pages["Config"].startswith("# Config")

    def test_skips_short_sections(self, tmp_path):
        content = "## Short\n\nToo short\n\n## Long\n\n" + ("x" * 250)
        p = tmp_path / "design.md"
        p.write_text(content)
        pages = _split_design_md(str(p))
        assert "Short" not in pages
        assert "Long" in pages

    def test_nonexistent_file(self):
        pages = _split_design_md("/nonexistent/design.md")
        assert pages == {}

    def test_heading_slug_strips_special_chars(self, tmp_path):
        content = "## My Cool Section! (v2)\n\n" + ("x" * 250)
        p = tmp_path / "design.md"
        p.write_text(content)
        pages = _split_design_md(str(p))
        assert "My-Cool-Section-v2" in pages


