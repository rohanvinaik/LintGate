# ── impl_project_wiki_read ──────────────────────────────────────────


class TestImplProjectWikiRead:
    def _helpers(self) -> dict[str, Any]:
        return {"_validate_project_root": MagicMock()}

    @patch("mcp_tools._gh_wiki_impl._repo_full_name", return_value="")
    def test_no_remote(self, mock_rfn):
        result = impl_project_wiki_read("/tmp/test", "Theory-Profile", self._helpers())
        assert "error" in result

    @patch("mcp_tools._gh_wiki_impl._repo_full_name", return_value="owner/repo")
    def test_local_wiki_exists(self, _rfn, tmp_path):
        wiki_dir = tmp_path / ".lintgate" / "wiki"
        wiki_dir.mkdir(parents=True)
        (wiki_dir / "Theory-Profile.md").write_text("# Local content")
        result = impl_project_wiki_read(str(tmp_path), "Theory-Profile", self._helpers())
        assert result["source"] == "local"
        assert result["content"] == "# Local content"
        assert result["page"] == "Theory-Profile"
        assert result["repo"] == "owner/repo"

    @patch("mcp_tools._gh_wiki_impl._read_remote_wiki_page", return_value={"source": "remote"})
    @patch("mcp_tools._gh_wiki_impl._repo_full_name", return_value="owner/repo")
    def test_falls_to_remote(self, _rfn, mock_remote, tmp_path):
        result = impl_project_wiki_read(str(tmp_path), "Theory-Profile", self._helpers())
        assert result["source"] == "remote"
        mock_remote.assert_called_once_with(str(tmp_path), "owner/repo", "Theory-Profile")


# ── _read_remote_wiki_page ──────────────────────────────────────────


class TestReadRemoteWikiPage:
    @patch("mcp_tools._gh_wiki_impl._clone_wiki", return_value={"error": "clone failed"})
    def test_clone_error(self, mock_clone):
        result = _read_remote_wiki_page("/path", "owner/repo", "Page")
        assert "error" in result
        assert result["error"] == "clone failed"
        assert "hint" in result

    @patch("mcp_tools._gh_wiki_impl.shutil.rmtree")
    @patch("mcp_tools._gh_wiki_impl.tempfile.mkdtemp")
    @patch("mcp_tools._gh_wiki_impl._clone_wiki", return_value={"ok": True})
    def test_page_not_found(self, mock_clone, mock_mkdtemp, mock_rmtree, tmp_path):
        mock_mkdtemp.return_value = str(tmp_path)
        # Create a different page so we get available_pages
        (tmp_path / "Home.md").write_text("home")
        (tmp_path / ".hidden.md").write_text("hidden")
        result = _read_remote_wiki_page("/path", "owner/repo", "Nonexistent")
        assert "error" in result
        assert "not found" in result["error"]
        assert "Home" in result["available_pages"]
        assert ".hidden" not in result["available_pages"]

    @patch("mcp_tools._gh_wiki_impl.shutil.rmtree")
    @patch("mcp_tools._gh_wiki_impl.tempfile.mkdtemp")
    @patch("mcp_tools._gh_wiki_impl._clone_wiki", return_value={"ok": True})
    def test_page_found(self, mock_clone, mock_mkdtemp, mock_rmtree, tmp_path):
        mock_mkdtemp.return_value = str(tmp_path)
        (tmp_path / "Theory-Profile.md").write_text("# Theory content")
        result = _read_remote_wiki_page("/path", "owner/repo", "Theory-Profile")
        assert result["source"] == "remote"
        assert result["content"] == "# Theory content"
        assert result["page"] == "Theory-Profile"
        assert "next_actions" in result
