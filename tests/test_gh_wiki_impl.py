class TestWriteAndPushPages:
    @patch("mcp_tools._gh_wiki_impl._push_wiki", return_value={"ok": True})
    @patch("mcp_tools._gh_wiki_impl._clone_wiki", return_value={"ok": True})
    def test_success(self, mock_clone, mock_push):
        pages = {"Test-Page": "# Test\n\nContent here."}
        result = _write_and_push_pages("/path", "owner/repo", "theory", pages)
        assert result["write"] is True
        assert result["pages_written"] == 1
        assert result["page_names"] == ["Test-Page"]
        assert result["push_result"] == {"ok": True}
        assert "next_actions" in result
        mock_clone.assert_called_once()
        mock_push.assert_called_once()

    @patch("mcp_tools._gh_wiki_impl._clone_wiki", return_value={"error": "clone failed"})
    def test_clone_error(self, mock_clone):
        result = _write_and_push_pages("/path", "owner/repo", "theory", {"p": "c"})
        assert "error" in result
        assert result["error"] == "clone failed"
        assert "hint" in result

    @patch("mcp_tools._gh_wiki_impl._push_wiki", return_value={"ok": True})
    @patch("mcp_tools._gh_wiki_impl._clone_wiki", return_value={"ok": True})
    def test_writes_files_to_tmpdir(self, mock_clone, mock_push):
        pages = {"Page-A": "aaa", "Page-B": "bbb"}
        result = _write_and_push_pages("/path", "owner/repo", "all", pages)
        assert result["pages_written"] == 2
        assert sorted(result["page_names"]) == ["Page-A", "Page-B"]


