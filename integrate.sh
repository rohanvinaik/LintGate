# ── Run ───────────────────────────────────────────────────────────────────
header "LintGate Agent Integration"

if [[ "$CLEAN" == true ]]; then
    echo "Cleaning generated agent config files..."
    for agent in "${!AGENTS[@]}"; do
        IFS=':' read -r _ _ clean_fn <<< "${AGENTS[$agent]}"
        $clean_fn
    done
    echo ""
    echo "Done. AGENTS.md and .claude/CLAUDE.md preserved."
    exit 0
fi

# Detect
echo "Scanning for LLM coding agents..."
for agent in $(echo "${!AGENTS[@]}" | tr ' ' '\n' | sort); do
    IFS=':' read -r detect_fn _ _ <<< "${AGENTS[$agent]}"
    if $detect_fn 2>/dev/null; then
        DETECTED_AGENTS+=("$agent")
        log "Found: $agent"
    fi
done

if [[ ${#DETECTED_AGENTS[@]} -eq 0 ]]; then
    echo ""
    echo "No agents detected. AGENTS.md is still readable by any agent."
    echo "Re-run after installing a coding agent, or use --agent NAME to force."
    exit 0
fi

if [[ "$LIST_ONLY" == true ]]; then
    echo ""
    echo "Detected agents: ${DETECTED_AGENTS[*]}"
    echo "Run without --list to generate config files."
    exit 0
fi

# Generate
echo ""
echo "Generating agent config files..."
if [[ -n "$ONLY_AGENT" ]]; then
    if [[ -v "AGENTS[${ONLY_AGENT}]" ]]; then
        IFS=':' read -r _ gen_fn _ <<< "${AGENTS[$ONLY_AGENT]}"
        $gen_fn
    else
        echo "Unknown agent: $ONLY_AGENT"
        echo "Known agents: ${!AGENTS[*]}"
        exit 1
    fi
else
    for agent in "${DETECTED_AGENTS[@]}"; do
        IFS=':' read -r _ gen_fn _ <<< "${AGENTS[$agent]}"
        $gen_fn
    done
fi

# Summary
echo ""
header "Integration Complete"
echo ""
echo "Detected agents:  ${DETECTED_AGENTS[*]}"
echo "Generated files:  ${#ALL_GENERATED_FILES[@]}"
echo "Source of truth:   AGENTS.md"
echo ""
echo "Every generated file is a pointer to AGENTS.md."
echo "To update instructions, edit AGENTS.md — all agents read it."
echo "To regenerate: bash integrate.sh"
echo "To clean up:   bash integrate.sh --clean"
