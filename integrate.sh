#!/usr/bin/env bash
# LintGate Agent Integration — the Symbiote script.
#
# Detects which LLM coding agents are present on this system and generates
# the appropriate config files so each agent auto-discovers LintGate.
#
# Design principle: AGENTS.md is the single source of truth. Every generated
# file either sym-links to it or contains a minimal pointer that says
# "read AGENTS.md." No content is duplicated across agent-specific files.
#
# Usage:
#   bash integrate.sh              # Auto-detect and configure all found agents
#   bash integrate.sh --list       # List detected agents without writing anything
#   bash integrate.sh --clean      # Remove all generated agent config files
#   bash integrate.sh --agent X    # Configure only agent X (claude, cursor, copilot, windsurf, etc.)
#
# Called automatically by setup.sh. Safe to re-run — idempotent.
set -euo pipefail

LINTGATE_DIR="$(cd "$(dirname "$0")" && pwd)"
AGENTS_MD="$LINTGATE_DIR/AGENTS.md"
GENERATED_MARKER="# AUTO-GENERATED by LintGate integrate.sh — do not edit manually."
DRY_RUN=false
LIST_ONLY=false
CLEAN=false
ONLY_AGENT=""

# ── Parse args ────────────────────────────────────────────────────────────
while [[ $# -gt 0 ]]; do
    case $1 in
        --list)     LIST_ONLY=true; shift ;;
        --clean)    CLEAN=true; shift ;;
        --dry-run)  DRY_RUN=true; shift ;;
        --agent)    ONLY_AGENT="$2"; shift 2 ;;
        *)          echo "Unknown option: $1"; exit 1 ;;
    esac
done

# ── Agent registry ────────────────────────────────────────────────────────
# Each entry: detect function, generate function, cleanup paths
declare -a DETECTED_AGENTS=()
declare -a ALL_GENERATED_FILES=()

log() { echo "  $1"; }
header() { echo ""; echo "=== $1 ==="; }

is_generated() {
    local file="$1"
    [[ -f "$file" ]] && head -1 "$file" 2>/dev/null | grep -q "AUTO-GENERATED by LintGate" && return 0
    [[ -L "$file" ]] && return 0  # sym-links we created
    return 1
}

# ── Pointer file generator ────────────────────────────────────────────────
# Instead of duplicating AGENTS.md content, each agent-specific file is a
# minimal pointer: the marker line + "read AGENTS.md for everything."
generate_pointer() {
    local file="$1"
    local agent_name="$2"
    local extra_notes="${3:-}"

    if [[ "$DRY_RUN" == true ]]; then
        log "[dry-run] Would create $file"
        return
    fi

    mkdir -p "$(dirname "$file")"
    cat > "$file" << POINTER_EOF
$GENERATED_MARKER
# Re-generate with: bash integrate.sh --agent $agent_name
#
# LintGate — Real-time quality supervision for AI-generated code.
#
# This file exists so $agent_name auto-discovers LintGate.
# ALL instructions, tool references, and conventions live in AGENTS.md.
# Read AGENTS.md — it is the single source of truth.
#
# Quick start (if LintGate MCP tools are available):
#   1. build_theory_pack  — orient to the project's theory profile
#   2. controlplane_run   — full supervision mesh
#   3. behavior_precheck  — register predictions before Bash commands
#
# Full tool reference: AGENTS.md (28 tools by cognitive mode)
# Quick orientation: SKILL.md
# Design deep dive: docs/design.md
$extra_notes
POINTER_EOF
    ALL_GENERATED_FILES+=("$file")
    log "Created $file"
}

# ── Cognitive context generator (Tier 2) ──────────────────────────────────
# For agents that support deeper context (not just a pointer), generate
# a starter cognitive context file with dispositions and guardrails adapted
# from the Claude Code experience. These are NOT pointer files — they contain
# real cognitive guidance that helps the agent reason about LintGate.
generate_cognitive_context() {
    local file="$1"
    local agent_name="$2"

    if [[ "$DRY_RUN" == true ]]; then
        log "[dry-run] Would create $file (cognitive context)"
        return
    fi

    # Don't overwrite if user has customized it
    if [[ -f "$file" ]] && ! is_generated "$file"; then
        log "$file exists (user-customized) — not overwriting"
        return
    fi

    mkdir -p "$(dirname "$file")"
    cat > "$file" << 'COGNITIVE_EOF'
# AUTO-GENERATED by LintGate integrate.sh — do not edit manually.
# Re-generate with: bash integrate.sh
# Customize freely — once edited, integrate.sh will not overwrite.
#
# LintGate Cognitive Context
#
# This file teaches you HOW TO THINK when working with LintGate.
# For WHAT TOOLS TO USE, read AGENTS.md.

## Know Your Epistemic State

Before acting on a file you haven't read, before trying a third approach,
before ignoring a behavioral finding — ask yourself:

- **Do I have theory context?** If not → `build_theory_pack`. The theory profile
  tells you what this project values. Without it you are guessing at alignment.
- **What is my prediction accuracy?** If `behavior_precheck` shows accuracy below
  50% after 5+ predictions, your mental model of the project's constraints is wrong.
  Stop and re-orient.
- **What is the coherence state?** If `controlplane_run` shows cross-channel
  disagreement (lint + tests + git pointing at the same files), that convergence
  IS the diagnosis. Read it.

## Dispositions

**When starting a session** — orient first. Call `build_theory_pack` or
`controlplane_status`. The 200 tokens you spend orienting prevent the 2,000
tokens you spend on a doomed approach.

**When acting** — register predictions. Before any Bash command, call
`behavior_precheck` with a structured prediction. This builds the accuracy
signal that modulates behavioral finding confidence.

**When stuck** — DO NOT try variant #4. If you have cycled through 3 approaches,
your problem is not execution — it is understanding. Run `behavior_precheck` to
see your constraint coverage.

**When the system speaks** — findings are weather reports, not commands. But if
you ignore a hard signal and try the same pattern again, the system will escalate.

## Guardrails

- DO NOT disable lint channels globally to hide regressions.
- DO NOT auto-apply generated repairs without explicit acceptance.
- DO NOT try a 4th approach without running `behavior_precheck` first.
- MUST keep hook and MCP outputs machine-readable and stable.
- MUST update AGENTS.md, README.md, and docs/design.md when changing MCP tools.

## References

- Tool reference: AGENTS.md (28 tools by cognitive mode)
- Architecture of Inquiry: .claude/rules/inquiry.md
- Design deep dive: docs/design.md
COGNITIVE_EOF
    ALL_GENERATED_FILES+=("$file")
    log "Created $file (cognitive context — Tier 2)"
}

# ── Agent: Claude Code ────────────────────────────────────────────────────
detect_claude() {
    # Claude Code reads .claude/CLAUDE.md and CLAUDE.md hierarchically
    # It also reads AGENTS.md natively as of 2025
    [[ -d "$HOME/.claude" ]] || command -v claude &>/dev/null
}

generate_claude() {
    # CLAUDE.md is special — it has managed sections for living context,
    # so we DON'T generate or overwrite it. We just verify it exists.
    local claude_md="$LINTGATE_DIR/.claude/CLAUDE.md"
    if [[ -f "$claude_md" ]]; then
        if is_generated "$claude_md"; then
            log "CLAUDE.md is auto-generated — will leave as-is (has managed sections)"
        else
            log "CLAUDE.md exists (hand-maintained with managed sections) — not touching"
        fi
    else
        log "WARNING: .claude/CLAUDE.md missing. Run: bash setup.sh"
    fi
}

clean_claude() {
    # Never clean CLAUDE.md — it has managed sections that accumulate state
    log "CLAUDE.md preserved (has managed sections — never auto-cleaned)"
}

# ── Agent: Cursor ─────────────────────────────────────────────────────────
detect_cursor() {
    # Cursor reads .cursorrules (legacy) and .cursor/rules/*.mdc (current)
    command -v cursor &>/dev/null || [[ -d "$HOME/.cursor" ]] || [[ -d "$HOME/Library/Application Support/Cursor" ]]
}

generate_cursor() {
    # Modern Cursor uses .cursor/rules/*.mdc with YAML frontmatter
    local rules_dir="$LINTGATE_DIR/.cursor/rules"
    local mdc_file="$rules_dir/lintgate.mdc"
    local legacy_file="$LINTGATE_DIR/.cursorrules"

    if [[ "$DRY_RUN" == true ]]; then
        log "[dry-run] Would create $mdc_file and $legacy_file"
        return
    fi

    mkdir -p "$rules_dir"

    # Modern .mdc format with YAML frontmatter
    cat > "$mdc_file" << 'MDC_EOF'
---
description: LintGate quality supervision system
alwaysApply: true
---
# AUTO-GENERATED by LintGate integrate.sh — do not edit manually.
# Re-generate with: bash integrate.sh --agent cursor

Read AGENTS.md for the full LintGate tool reference (28 tools by cognitive mode).
Read SKILL.md for quick orientation. Read docs/design.md for architecture.

Key rules:
- Update AGENTS.md + README.md + docs/design.md when changing MCP tools
- Source of truth: `grep -c "@mcp.tool()" mcp_server.py`
- DO NOT disable lint channels globally
- DO NOT auto-apply repairs without acceptance

If LintGate MCP tools are available, start with:
1. build_theory_pack → 2. controlplane_run → 3. behavior_precheck
MDC_EOF
    ALL_GENERATED_FILES+=("$mdc_file")
    log "Created $mdc_file (modern .mdc format)"

    # Legacy .cursorrules for older Cursor versions
    generate_pointer "$legacy_file" "cursor"
}

clean_cursor() {
    local mdc="$LINTGATE_DIR/.cursor/rules/lintgate.mdc"
    local legacy="$LINTGATE_DIR/.cursorrules"
    for f in "$mdc" "$legacy"; do
        if is_generated "$f"; then
            rm -f "$f"
            log "Removed $f"
        fi
    done
    # Clean up empty .cursor/rules/ dir
    [[ -d "$LINTGATE_DIR/.cursor/rules" ]] && rmdir "$LINTGATE_DIR/.cursor/rules" 2>/dev/null || true
    [[ -d "$LINTGATE_DIR/.cursor" ]] && rmdir "$LINTGATE_DIR/.cursor" 2>/dev/null || true
}

